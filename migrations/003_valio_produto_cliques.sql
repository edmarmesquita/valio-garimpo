-- Execute manualmente no SQL Editor do Supabase do Valiô. Não há dados pessoais nesta tabela.
create table if not exists public.produto_cliques (
  id bigint generated by default as identity primary key,
  mercado_livre_id text not null check (mercado_livre_id ~ '^MLB[0-9]+$'),
  clicked_at timestamptz not null default now(),
  origem text null check (origem in ('vitrine', 'busca', 'colecao')),
  categoria text null check (categoria in (
    'Achados para Casa', 'Achados para Maridos',
    'Achados para Elas', 'Achados para Presentear'
  ))
);

create index if not exists produto_cliques_mercado_livre_id_idx
  on public.produto_cliques (mercado_livre_id);
create index if not exists produto_cliques_clicked_at_idx
  on public.produto_cliques (clicked_at);

alter table public.produto_cliques enable row level security;
revoke all on public.produto_cliques from public, anon, authenticated;
grant select, insert on public.produto_cliques to service_role;
revoke all on sequence public.produto_cliques_id_seq from public, anon, authenticated;
grant usage, select on sequence public.produto_cliques_id_seq to service_role;

-- Agregação por produto, categoria registrada e dia local de São Paulo.
create or replace view public.produto_cliques_diario
  with (security_invoker = true) as
select mercado_livre_id, categoria,
  (clicked_at at time zone 'America/Sao_Paulo')::date as dia,
  count(*)::bigint as cliques
from public.produto_cliques
group by mercado_livre_id, categoria, (clicked_at at time zone 'America/Sao_Paulo')::date;

revoke all on public.produto_cliques_diario from public, anon, authenticated;
grant select on public.produto_cliques_diario to service_role;
