-- Execute manualmente no SQL Editor do Supabase do Valiô.
create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  mercado_livre_id text not null unique,
  titulo text not null,
  descricao text not null default '',
  preco numeric(12, 2) not null check (preco > 0),
  data_preco text not null check (data_preco ~ '^\d{2}/\d{2}/\d{4}$'),
  link_afiliado text not null,
  categoria text not null check (categoria in (
    'Achados para Casa', 'Achados para Maridos',
    'Achados para Elas', 'Achados para Presentear'
  )),
  rating numeric(2, 1) check (rating between 0 and 5),
  imagem text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (length(btrim(mercado_livre_id)) > 0),
  check (length(btrim(titulo)) > 0),
  check (length(btrim(link_afiliado)) > 0),
  check (length(btrim(imagem)) > 0)
);

alter table public.produtos enable row level security;

grant select, insert, update on public.produtos to service_role;
grant usage, select on sequence public.produtos_id_seq to service_role;
grant select on public.produtos to anon, authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'produtos'
      and policyname = 'produtos_ativos_publicos'
  ) then
    create policy produtos_ativos_publicos on public.produtos
      for select to anon, authenticated using (ativo = true);
  end if;
end $$;
